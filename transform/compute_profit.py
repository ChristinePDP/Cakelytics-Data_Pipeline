"""
TRANSFORM — Business-ready output tables

Applies the derivation rules B-04 to B-09 and builds the two output tables
that are handed over to the Load stage:

  dim_date             one row per business date (surrogate key: date_key, natural key: full_date)
  fact_daily_summary   one row per business date with the daily measures

The smart surrogate key date_key (YYYYMMDD integer) is generated here to link
fact_daily_summary to dim_date. The warehouse surrogate key summary_key is
generated by the warehouse (SERIAL) when loaded.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

import pandas as pd

from transform.rules import MONEY_STEP
from utils.batch import Batch


def compute_profit(total_sales: Decimal, total_expenses: Decimal) -> Decimal:
    """B-08: profit = total_sales - total_expenses."""
    return (total_sales - total_expenses).quantize(MONEY_STEP)


def build_output_tables(
    batch: Batch, total_sales: Decimal, waste_cost: Decimal, inventory_cost: Decimal
) -> dict[str, pd.DataFrame]:
    total_expenses = (waste_cost + inventory_cost).quantize(MONEY_STEP)   # B-07
    profit = compute_profit(total_sales, total_expenses)                  # B-08
    day = date.fromisoformat(batch.batch_date)
    date_key = int(day.strftime("%Y%m%d"))                                # B-09 surrogate key

    dim_date = pd.DataFrame([{                                            # B-09
        "date_key": date_key,
        "full_date": batch.batch_date,
        "day": day.day,
        "month": day.month,
        "year": day.year,
    }])

    fact_daily_summary = pd.DataFrame([{
        "date_key": date_key,
        "full_date": batch.batch_date,
        "total_sales": total_sales.quantize(MONEY_STEP),                  # B-04
        "total_expenses": total_expenses,
        "profit": profit,
    }])

    return {"dim_date": dim_date, "fact_daily_summary": fact_daily_summary}
